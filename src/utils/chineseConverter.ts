export function autoConvertToSimplified(input: string): string {
  if (!input) return '';
  let result = '';
  for (const char of input) {
    result += TC_TO_SC_MAP[char] || char;
  }
  return result;
}

export function hasTraditionalCharacters(input: string): boolean {
  if (!input) return false;
  for (const char of input) {
    if (TC_TO_SC_MAP[char]) return true;
  }
  return false;
}

